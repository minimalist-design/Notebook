// Copies self-hosted fonts, KaTeX and Mermaid from node_modules into
// resources/public and generates resources/public/css/fonts.css.
import { cpSync, mkdirSync, readdirSync, writeFileSync, existsSync, rmSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const nm = join(root, "node_modules");
const pub = join(root, "resources", "public");
const fontsOut = join(pub, "fonts");
const vendorOut = join(pub, "vendor");

rmSync(fontsOut, { recursive: true, force: true });
rmSync(vendorOut, { recursive: true, force: true });
mkdirSync(fontsOut, { recursive: true });
mkdirSync(vendorOut, { recursive: true });

const weights = {
  Thin: 100, ExtraLight: 200, Light: 300, Regular: 400, Text: 450,
  Medium: 500, SemiBold: 600, Bold: 700,
};

const faces = [];

// --- Variable families: Sans + Serif (100–700 on one axis) -----------------
for (const [pkg, family, prefix] of [
  ["plex-sans-variable", "IBM Plex Sans", "IBM Plex Sans Var"],
  ["plex-serif-variable", "IBM Plex Serif", "IBM Plex Serif Var"],
]) {
  const src = join(nm, "@ibm", pkg, "fonts", "complete", "woff2");
  const dir = join(fontsOut, pkg);
  mkdirSync(dir, { recursive: true });
  for (const style of ["Roman", "Italic"]) {
    const file = `${prefix.replace(/ /g, "")}-${style}.woff2`;
    cpSync(join(src, `${prefix}-${style}.woff2`), join(dir, file));
    faces.push(`@font-face {
  font-family: "${family}";
  font-style: ${style === "Italic" ? "italic" : "normal"};
  font-weight: 100 700;
  font-display: swap;
  src: url("/fonts/${pkg}/${file}") format("woff2-variations"),
       url("/fonts/${pkg}/${file}") format("woff2");
}`);
  }
  cpSync(join(src, "license.txt"), join(dir, "LICENSE.txt"));
}

// --- Static families: Mono + Sans Condensed (all weights + italics) --------
for (const [pkg, family, prefix] of [
  ["plex-mono", "IBM Plex Mono", "IBMPlexMono"],
  ["plex-sans-condensed", "IBM Plex Sans Condensed", "IBMPlexSansCondensed"],
]) {
  const src = join(nm, "@ibm", pkg, "fonts", "complete", "woff2");
  const dir = join(fontsOut, pkg);
  mkdirSync(dir, { recursive: true });
  for (const f of readdirSync(src).filter((f) => f.endsWith(".woff2"))) {
    const m = f.match(new RegExp(`^${prefix}-(\\w+?)(Italic)?\\.woff2$`));
    if (!m) continue;
    let [, w, italic] = m;
    if (w === "Italic" && !italic) { w = "Regular"; italic = "Italic"; }
    if (!(w in weights)) continue;
    cpSync(join(src, f), join(dir, f));
    faces.push(`@font-face {
  font-family: "${family}";
  font-style: ${italic ? "italic" : "normal"};
  font-weight: ${weights[w]};
  font-display: swap;
  src: url("/fonts/${pkg}/${f}") format("woff2");
}`);
  }
  cpSync(join(src, "license.txt"), join(dir, "LICENSE.txt"));
}

// --- Plex Math ---------------------------------------------------------------
{
  const src = join(nm, "@ibm", "plex-math", "fonts", "complete", "woff2");
  const dir = join(fontsOut, "plex-math");
  mkdirSync(dir, { recursive: true });
  cpSync(join(src, "IBMPlexMath-Regular.woff2"), join(dir, "IBMPlexMath-Regular.woff2"));
  cpSync(join(src, "license.txt"), join(dir, "LICENSE.txt"));
  faces.push(`@font-face {
  font-family: "IBM Plex Math";
  font-style: normal;
  font-weight: 400;
  font-display: swap;
  src: url("/fonts/plex-math/IBMPlexMath-Regular.woff2") format("woff2");
}`);
}

mkdirSync(join(pub, "css"), { recursive: true });
writeFileSync(
  join(pub, "css", "fonts.css"),
  `/* Generated by scripts/vendor.mjs — do not edit. IBM Plex is SIL OFL 1.1. */\n${faces.join("\n")}\n`
);

// --- KaTeX + Mermaid ---------------------------------------------------------
cpSync(join(nm, "katex", "dist", "katex.min.css"), join(vendorOut, "katex", "katex.min.css"));
cpSync(join(nm, "katex", "dist", "fonts"), join(vendorOut, "katex", "fonts"), { recursive: true });
cpSync(join(nm, "mermaid", "dist", "mermaid.min.js"), join(vendorOut, "mermaid", "mermaid.min.js"));

if (!existsSync(join(pub, "css", "fonts.css"))) throw new Error("fonts.css not written");
console.log(`vendor: ${faces.length} @font-face rules, KaTeX and Mermaid copied`);
